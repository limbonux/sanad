(function(){
  function getLang(){ return localStorage.getItem('sanad-lang') || 'ar'; }
  function apply(lang){
    var dict = window.SANAD_DICT[lang] || window.SANAD_DICT.ar;
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'en' ? 'ltr' : 'rtl';
    document.querySelectorAll('[data-i18n]').forEach(function(el){
      var k = el.getAttribute('data-i18n');
      if(dict[k] !== undefined) el.textContent = dict[k];
    });
    document.querySelectorAll('[data-i18n-html]').forEach(function(el){
      var k = el.getAttribute('data-i18n-html');
      if(dict[k] !== undefined) el.innerHTML = dict[k];
    });
    document.querySelectorAll('[data-i18n-attr]').forEach(function(el){
      el.getAttribute('data-i18n-attr').split(';').forEach(function(pair){
        var idx = pair.indexOf(':');
        var attr = pair.slice(0, idx), k = pair.slice(idx + 1);
        if(dict[k] !== undefined) el.setAttribute(attr, dict[k]);
      });
    });
    if(dict['page.title_home']!==undefined || document.querySelector('[data-i18n-title]')){
      var titleEl = document.querySelector('[data-i18n-title]');
      if(titleEl){
        var tk = titleEl.getAttribute('data-i18n-title');
        if(dict[tk] !== undefined) document.title = dict[tk];
      }
    }
    document.querySelectorAll('.lang-toggle').forEach(function(btn){
      btn.textContent = dict['lang.toggle'];
    });
    localStorage.setItem('sanad-lang', lang);
  }
  window.SanadI18n = {
    get: getLang,
    apply: apply,
    toggle: function(){ apply(getLang() === 'ar' ? 'en' : 'ar'); }
  };
  document.addEventListener('DOMContentLoaded', function(){
    apply(getLang());
    document.querySelectorAll('.lang-toggle').forEach(function(btn){
      btn.addEventListener('click', function(e){
        e.preventDefault();
        window.SanadI18n.toggle();
      });
    });
  });
})();
